// Generates src/data/photos.generated.ts from assets/photos/credits.json.
// Every bundled photo keeps its author, licence and source URL for attribution.
import fs from 'node:fs';
const credits = JSON.parse(fs.readFileSync('assets/photos/credits.json', 'utf8'));
const keys = Object.keys(credits).filter((k) => fs.existsSync(`assets/photos/${k}.jpg`));
const clean = (s) => s.replace(/\s+/g, ' ').replace(/^Photo:\s*/i, '').trim();
let out = `// AUTO-GENERATED by scripts/build-photo-registry.mjs — do not edit.\nimport type { PhotoAsset } from '@/types/domain';\n\nexport const bundledPhotos: Record<string, PhotoAsset> = {\n`;
for (const k of keys) {
  const c = credits[k];
  out += `  ${JSON.stringify(k)}: { id: ${JSON.stringify(k)}, source: require('../../assets/photos/${k}.jpg'), author: ${JSON.stringify(clean(c.author) || 'Unknown')}, license: ${JSON.stringify(c.license)}, sourceUrl: ${JSON.stringify(c.source)}, title: ${JSON.stringify(c.title)}, isDemo: true },\n`;
}
out += `};\n`;
fs.writeFileSync('src/data/photos.generated.ts', out);
console.log(`Wrote ${keys.length} photos`);
